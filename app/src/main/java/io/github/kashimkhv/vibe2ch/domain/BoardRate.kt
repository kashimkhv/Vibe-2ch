package io.github.kashimkhv.vibe2ch.domain

import io.github.kashimkhv.vibe2ch.domain.model.ThreadSummary
import io.github.kashimkhv.vibe2ch.domain.model.ThreadsPage

/**
 * Активность доски — постов в час.
 *
 * Главный источник — сам движок: в каждом файле страницы он присылает
 * `board_speed`, посчитанный по всей доске и всей истории постов. Так же
 * поступает Dashchan: в `DvachChanPerformer.onReadThreads` поле читается и
 * показывается как «N сообщений в час» без всякой клиентской арифметики.
 * Считать своё имеет смысл только когда поля нет (зеркало, старый движок).
 *
 * Своя оценка по первой странице устроена так:
 *
 * - складываются **текущие скорости** тредов, а не посты и не средние за жизнь:
 *   у каждого треда в ленте есть три последних поста с временем, значит есть
 *   два интервала и их длительность. У живого окно короткое, у спящего —
 *   длинное, и его вклад сам стремится к нулю, без порогов «активен/не активен»;
 * - сумма скоростей, а не «постов на всё время через общий интервал»: иначе
 *   один тред с сотней постов за неделю перевесил бы двадцать живых;
 * - средняя за жизнь не годится как основная мера: тред, который бурлил вчера,
 *   по ней остаётся быстрым, хотя сейчас стоит. Она остаётся запасным
 *   вариантом, когда последних постов меньше двух и интервал не измерить.
 *
 * Два интервала — слишком маленькая выборка: три поста за минуту дали бы
 * сотню постов в час, и одна такая вспышка перевесила бы всю доску. Поэтому к
 * хвосту добавляется один «фиктивный» интервал со средней скоростью треда
 * (сглаживание по Байесу, априорное распределение с α = 1). Для треда, который
 * пишет ровно со своей средней скоростью, формула возвращает ту же среднюю —
 * она не смещает оценку, только гасит выбросы.
 *
 * Своя оценка — заведомо неполная: в ленте видна только первая страница
 * (двадцать самых свежих тредов), посты в глубине доски в неё не попадают,
 * а у каждого треда движок отдаёт не больше трёх последних постов. Поэтому она
 * показывается со знаком «≈», а число движка — как есть.
 */
data class BoardActivity(
    val postsPerHour: Double,
    /** Число посчитано клиентом по первой странице, а не прислано движком. */
    val isEstimate: Boolean,
)

/**
 * Активность доски: `board_speed` движка, а без него — своя оценка по тредам
 * страницы.
 */
fun boardActivity(page: ThreadsPage): BoardActivity =
    if (page.boardSpeed > 0) {
        BoardActivity(page.boardSpeed.toDouble(), isEstimate = false)
    } else {
        BoardActivity(postsPerHourOf(page.threads), isEstimate = true)
    }

/** Своя оценка: сумма текущих скоростей тредов страницы. */
fun postsPerHourOf(threads: List<ThreadSummary>): Double =
    threads.sumOf { threadPostsPerHour(it) }

/**
 * Скорость одного треда: два интервала между тремя последними постами,
 * сглаженные средней за жизнь. Без двух отметок времени — средняя за жизнь,
 * для треда из одного ОП — ноль.
 */
fun threadPostsPerHour(thread: ThreadSummary): Double {
    // Средняя за жизнь — и запасной вариант, и априорная скорость для сглаживания.
    // У треда из одного поста жизни ещё нет: делить не на что.
    val lifetime = if (thread.postsCount > 1) replyRate(thread) else 0.0

    // Порядок и дубли в ответах не гарантированы: чистим и сортируем, иначе
    // отрицательный или нулевой интервал дал бы бесконечность.
    val tail = thread.replies
        .map { it.timestamp }
        .filter { it > 0 }
        .distinct()
        .sorted()
        // В ленте движок отдаёт три последних поста, но доменная функция не
        // должна полагаться на это: берём хвост сама.
        .takeLast(3)
    if (tail.size >= 2) {
        // Время движка — в секундах: интервал в часах, а не в миллисекундах.
        val spanHours = (tail.last() - tail.first()) / 3_600.0
        if (spanHours > 0) {
            return if (lifetime > 0) {
                // k наблюдённых интервалов и один априорный (α = 1).
                tail.size / (spanHours + 1.0 / lifetime)
            } else {
                (tail.size - 1) / spanHours
            }
        }
    }
    return lifetime
}
