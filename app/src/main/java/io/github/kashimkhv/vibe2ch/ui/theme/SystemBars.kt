package io.github.kashimkhv.vibe2ch.ui.theme

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue

/**
 * Что текущий экран просит у системных баров.
 *
 * Обычно иконки часов и кнопок красит тема: в светлой они тёмные, в тёмной —
 * светлые, и это устраивает все экраны. Исключение одно — просмотрщик медиа:
 * он во весь экран и всегда чёрный, поэтому в светлой теме тёмные иконки на нём
 * не видны. Экран просит светлые иконки на время, пока открыт, а перекрашивает
 * бары одно место — `MainActivity`: там уже собрана вся логика системных баров
 * и она знает про выбранную тему.
 *
 * Просьба живёт в состоянии Compose, поэтому смена темы во время просмотра
 * (системная тема может переключиться по расписанию) пересчитывает бары снова
 * и не оставляет тёмные иконки на чёрном.
 */
object SystemBars {

    /** Светлые иконки поверх чёрного фона — независимо от темы интерфейса. */
    var lightIcons: Boolean by mutableStateOf(false)
}
