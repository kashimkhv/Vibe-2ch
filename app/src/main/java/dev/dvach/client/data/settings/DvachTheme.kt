package dev.dvach.client.data.settings

/**
 * Цветовая тема приложения. Названия — как у движка и в других клиентах двача:
 * Yotsuba, Photon, Tomorrow, Burchan и остальные узнаются по названию, поэтому
 * не переводим. «Material You» и «Monet» — это пара светлая/тёмная по умолчанию.
 *
 * Сам enum живёт в настройках, а не в `ui/theme`: выбор хранится в DataStore,
 * и слой данных не должен зависеть от Compose. Палитры и их роли — в
 * `ui/theme/Themes.kt`.
 *
 * @property id ключ в настройках: имя enum не годится, его нельзя менять, не
 *   ломая сохранённый выбор.
 * @property label подпись строки в списке тем.
 * @property hint чем тема отличается по восприятию: подсказка под названием,
 *   чтобы выбирать не по цветному квадратику, а по назначению.
 */
enum class DvachTheme(val id: String, val label: String, val hint: String) {
    /** Светлая или тёмная пара по настройке системы, а не своя палитра. */
    SYSTEM(
        "system",
        "Как в системе",
        "Светлая или тёмная пара Material You по настройке Android",
    ),

    /** Текущее оформление приложения: светлый фон и голубая шапка. */
    MATERIAL_LIGHT(
        "material_light",
        "Material You light",
        "Голубая шапка и белые строки — оформление по умолчанию",
    ),
    MATERIAL_DARK(
        "material_dark",
        "Material You dark",
        "Тёмно-синяя шапка, мягкий тёмный фон вместо чёрного",
    ),

    NOMIE(
        "nomie",
        "Nomie",
        "Графит и сирень: самый тихий из тёмных, без синего и коричневого",
    ),
    TOMORROW(
        "tomorrow",
        "Tomorrow",
        "Сине-серый фон, приглушённый текст — глаза не устают к концу треда",
    ),

    /** Чистый чёрный фон: на OLED-экранах чёрный пиксель не светится. */
    AMOLED(
        "amoled",
        "Amoled",
        "Чистый чёрный фон: пиксели OLED не светятся, батарея экономится",
    ),
    BURCHAN(
        "burchan",
        "Burchan",
        "Тёплая коричневая лампа: ни одной синей подсветки",
    ),
    HARDON(
        "hardon",
        "Hardon",
        "Бордовая шапка и розовые ссылки, текст остаётся спокойным",
    ),
    NEUTRON(
        "neutron",
        "Neutron",
        "Тёмно-синяя: шапка заметно темнее строк, граница видна без тени",
    ),
    PHOTON(
        "photon",
        "Photon",
        "Светлая холодная: голубоватый холст и тёмно-синие ссылки",
    ),
    YOTSUBA(
        "yotsuba",
        "Yotsuba A",
        "Кремовый фон и оранжевые ссылки — классика старого двача",
    ),
    TEPLO(
        "teplo",
        "teplo",
        "Тёплая светлая: бежевый фон, коричневый акцент, без синего",
    ),

    /** Тёмная пара к Material You: сиреневые акценты Monet. */
    MONET_DARK(
        "monet_dark",
        "Monet dark",
        "Тёмный сиреневый Material You с лавандовыми ссылками",
    ),
    AUTUMN(
        "autumn",
        "Autumn",
        "Янтарный акцент на тёмно-коричневом: осень без рыжины в тексте",
    ),

    /**
     * Ниже — темы редакторов кода: по ним айтишник узнаёт оформление
     * с первого взгляда. Фон, шапка и акценты канонические, а «мету»
     * (ники, даты) местами пришлось высветлить: канон рассчитан на код,
     * а не на длинный текст постов.
     */
    DRACULA(
        "dracula",
        "Dracula",
        "Фиолетовый фон и розовые ссылки — самая известная тёмная тема редакторов",
    ),
    NORD(
        "nord",
        "Nord",
        "Холодный арктический сине-серый: тише Tomorrow, без фиолетового",
    ),
    SOLARIZED_DARK(
        "solarized_dark",
        "Solarized Dark",
        "Тёмно-синий канон Solarized: точные цвета и мягкий контраст",
    ),
    GRUVBOX_DARK(
        "gruvbox_dark",
        "Gruvbox Dark",
        "Тёплый ретро-терминал: бежевый текст на коричневом, как в старом vim",
    ),
    CATPPUCCIN_MOCHA(
        "catppuccin_mocha",
        "Catppuccin Mocha",
        "Лавандовый фон и пастельные ссылки — самая свежая из тёмных",
    ),

    SOLARIZED_LIGHT(
        "solarized_light",
        "Solarized Light",
        "Кремовый светлый канон Solarized: тёплая бумага для дневного чтения",
    ),
    CATPPUCCIN_LATTE(
        "catppuccin_latte",
        "Catppuccin Latte",
        "Светлая пара к Mocha: прохладный серый холст, синие ссылки",
    ),
    ;

    companion object {
        /** Неизвестный или устаревший id — это не ошибка: показываем светлую тему. */
        fun fromId(id: String?): DvachTheme =
            entries.firstOrNull { it.id == id } ?: MATERIAL_LIGHT
    }
}
